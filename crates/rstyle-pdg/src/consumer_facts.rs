/// Availability of one prerequisite; an empty known value remains usable.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "status", content = "value", rename_all = "snake_case")]
pub enum Availability<T> {
    Known(T),
    Unknown { reason: String },
    Unsupported { reason: String },
    NotApplicable { reason: String },
}

/// Syntactic arity, including destructuring as one input and excluding `self`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Signature {
    pub parameters: usize,
    pub has_self: bool,
}

/// Independently available inputs for local consumers, borrowing captured bytes.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct LocalFacts<'a> {
    pub source: Availability<&'a str>,
    pub signature: Availability<Signature>,
}

/// Bind facts to their immutable selected-unit source without requiring a graph.
/// Contradictory evidence fails the query rather than yielding usable facts.
pub fn inspect(facts: &HirFnFacts) -> Result<LocalFacts<'_>, String> {
    match owned_source(facts)? {
        Availability::Known(_) => inspect_source(facts),
        Availability::Unknown { reason } => Ok(unavailable(reason)),
        Availability::Unsupported { reason } | Availability::NotApplicable { reason } => {
            Ok(LocalFacts {
                source: Availability::Unsupported { reason },
                signature: Availability::Unsupported {
                    reason: "Original signature is unavailable for expansion".into(),
                },
            })
        }
    }
}

// Source ownership checks do not parse syntax; bounded consumers run these first.
fn owned_source(facts: &HirFnFacts) -> Result<Availability<&str>, String> {
    if !facts.source.bytes.matches_identity(&facts.source.digest) {
        return Err("Local facts source checksum differs from captured bytes".into());
    }
    if facts.fn_span.end.checked_sub(facts.fn_span.start)
        != u32::try_from(facts.source.bytes.len()).ok()
    {
        return Err("Local facts function range differs from captured byte length".into());
    }
    if let Some(reason) = unavailable_owner(facts)? {
        return Ok(Availability::Unknown { reason });
    }

    if facts
        .source_diagnostics
        .iter()
        .any(|diagnostic| diagnostic.construct == "macro_generated_function")
    {
        return Ok(Availability::Unsupported {
            reason: "Function is generated by expansion".into(),
        });
    }
    Ok(Availability::Known(facts.source.bytes.as_str()))
}

fn inspect_source(facts: &HirFnFacts) -> Result<LocalFacts<'_>, String> {
    let source = facts.source.bytes.as_str();
    let function: syn::ItemFn = match syn::parse_str(source) {
        Ok(function) => function,
        Err(error) => {
            return Ok(LocalFacts {
                source: Availability::Known(source),
                signature: Availability::Unsupported {
                    reason: format!("Original function syntax is unavailable: {error}"),
                },
            });
        }
    };

    check_signature(facts, &function)?;
    let signature = if function.sig.variadic.is_some() {
        Availability::Unsupported {
            reason: "Variadic input has no fixed complete arity".into(),
        }
    } else {
        Availability::Known(Signature {
            parameters: function.sig.inputs.len() - usize::from(facts.signature.has_self),
            has_self: facts.signature.has_self,
        })
    };
    Ok(LocalFacts {
        source: Availability::Known(source),
        signature,
    })
}

fn unavailable(reason: String) -> LocalFacts<'static> {
    LocalFacts {
        source: Availability::Unknown {
            reason: reason.clone(),
        },
        signature: Availability::Unknown { reason },
    }
}

fn unavailable_owner(facts: &HirFnFacts) -> Result<Option<String>, String> {
    let options = &facts.build.frontend_options;
    let Some(context) = options.get(nominal_boundary::CONTEXT_KEY) else {
        return Ok(Some("Selected-unit context was not captured".into()));
    };
    let context: nominal_boundary::UnitContext =
        nominal_boundary::UnitContext::deserialize(context)
            .map_err(|error| format!("Invalid local facts context: {error}"))?;
    context.validate()?;

    if !options.contains_key(census::KEY) {
        return Ok(Some("Original source ownership was not captured".into()));
    }
    let census = options.data::<Arc<census::Census>>()?;
    check_census(&census, &context)?;
    check_file(facts, &census)
}

fn check_census(
    census: &census::Census,
    context: &nominal_boundary::UnitContext,
) -> Result<(), String> {
    if census.identity != census::IDENTITY || &census.context != context {
        return Err("Local facts source census has another identity or context".into());
    }
    if census.files.len() > census::MAX_FILES
        || census
            .files
            .iter()
            .try_fold(0usize, |total, file| total.checked_add(file.bytes.len()))
            .is_none_or(|total| total > census::MAX_BYTES)
    {
        return Err("Local facts source ownership exceeds its capture budget".into());
    }
    Ok(())
}

fn check_file(facts: &HirFnFacts, census: &census::Census) -> Result<Option<String>, String> {
    let options = &facts.build.frontend_options;
    let Some(path) = options
        .get("source_file")
        .and_then(serde_json::Value::as_str)
    else {
        return Ok(Some("Function source path was not captured".into()));
    };

    let mut files = census
        .files
        .iter()
        .filter(|file| file.path.to_str() == Some(path));
    let file = files
        .next()
        .ok_or("Local facts source file is absent from its census")?;
    if files.next().is_some() || !file.bytes.matches_identity(&file.digest) {
        return Err("Local facts source file is ambiguous or has inconsistent bytes".into());
    }
    if crate::source_evidence::byte_range(&file.bytes, facts.fn_span)?
        != facts.source.bytes.as_str()
    {
        return Err("Local facts source disagrees with its exact file range".into());
    }
    Ok(None)
}

fn check_signature(facts: &HirFnFacts, function: &syn::ItemFn) -> Result<(), String> {
    let signature = &function.sig;
    let source = facts.source.bytes.as_str();
    let has_self = signature.receiver().is_some();
    if let Some(identifier) = facts
        .build
        .frontend_options
        .get("source_identifier")
        .and_then(serde_json::Value::as_str)
        && signature.ident.to_string().trim_start_matches("r#") != identifier
    {
        return Err("Local facts signature belongs to another captured source identifier".into());
    }

    if signature.inputs.len() != facts.signature.params.len()
        || has_self != facts.signature.has_self
        || has_self != facts.signature.receiver.is_some()
        || signature.variadic.is_some() != facts.signature.is_variadic
        || header_span(source, function) != facts.signature.sig_span
    {
        return Err("Local facts signature disagrees with original input roster or span".into());
    }
    for (position, (syntax, captured)) in signature
        .inputs
        .iter()
        .zip(&facts.signature.params)
        .enumerate()
    {
        check_parameter(source, syntax, captured, position)?;
        if let syn::FnArg::Receiver(receiver) = syntax {
            check_receiver(facts, captured, receiver)?;
        }
    }
    Ok(())
}

// rustc's signature starts at visibility, while syn::Signature excludes it.
// Retain the signature end so bodies and intervening whitespace cannot widen it.
fn header_span(source: &str, function: &syn::ItemFn) -> ByteSpan {
    let signature = relative_span(source, function.sig.span());
    let start = match function.vis {
        syn::Visibility::Inherited => signature.start,
        _ => relative_span(source, function.vis.span()).start,
    };
    ByteSpan {
        start,
        end: signature.end,
    }
}

fn relative_span(source: &str, span: proc_macro2::Span) -> ByteSpan {
    ByteSpan {
        start: crate::source_evidence::byte_offset(source, span.start()) as u32,
        end: crate::source_evidence::byte_offset(source, span.end()) as u32,
    }
}

fn check_parameter(
    source: &str,
    syntax: &syn::FnArg,
    captured: &crate::ParamFact,
    position: usize,
) -> Result<(), String> {
    if captured.position as usize != position
        || captured.pat.param_index != Some(captured.position)
        || captured.name_span != captured.pat.span
        || crate::source_evidence::byte_range(source, captured.name_span)? != captured.pat.snippet
    {
        return Err("Local facts parameter position or pattern differs from original bytes".into());
    }
    if let syn::FnArg::Typed(argument) = syntax
        && (parameter_pattern_span(source, &argument.pat) != captured.name_span
            || relative_span(source, argument.ty.span()) != captured.ty_span)
    {
        return Err("Local facts parameter spans differ from original signature".into());
    }
    Ok(())
}

fn parameter_pattern_span(source: &str, pattern: &syn::Pat) -> ByteSpan {
    match pattern {
        syn::Pat::Ident(binding) if binding.by_ref.is_none() && binding.subpat.is_none() => {
            relative_span(source, binding.ident.span())
        }
        _ => relative_span(source, pattern.span()),
    }
}

fn check_receiver(
    facts: &HirFnFacts,
    captured: &crate::ParamFact,
    receiver: &syn::Receiver,
) -> Result<(), String> {
    let observed = facts
        .signature
        .receiver
        .as_ref()
        .ok_or("Missing captured receiver")?;
    let token = relative_span(&facts.source.bytes, receiver.self_token.span());
    if observed.span != captured.name_span
        || observed.snippet != captured.pat.snippet
        || token.start < observed.span.start
        || token.end > observed.span.end
    {
        return Err("Local facts receiver differs from original signature".into());
    }
    Ok(())
}
